const second = { id: 'test-other-' + suffix, email: 'other-' + suffix + '@example.test' };
const phone = n => '050' + String(Number(suffix) + n).padStart(7, '0').slice(-7);
async function call(path, who, body, expected = 200, extra = {}) {
 const headers = { ...(who ? { 'oai-authenticated-user-id': who.id, 'oai-authenticated-user-email': who.email } : {}), ...extra };
 if (body) headers['content-type'] = 'application/json';
 const response = await fetch(base + path, { method: body ? 'POST' : 'GET', headers, body: body ? JSON.stringify(body) : undefined });
 const data = await response.json();
 assert.equal(response.status, expected, path + ': ' + JSON.stringify(data));
 return data;
}
