import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
test('database isolates partners and enforces the commission ledger',async()=>{
 const db=new PGlite();
 await db.exec(`create role anon;create role authenticated;create schema auth;create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;`);
 await db.exec(await readFile(new URL('../supabase/schema.sql',import.meta.url),'utf8'));
 const owner='00000000-0000-4000-8000-000000000001',p1='00000000-0000-4000-8000-000000000002',p2='00000000-0000-4000-8000-000000000003';
 for(const [id,email]of [[owner,'owner@example.com'],[p1,'one@example.com'],[p2,'two@example.com']])await db.query('insert into auth.users values($1,$2,now())',[id,email]);
 const asUser=async(id)=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec('set role authenticated');};
 const call=async(action,payload)=>db.query('select public.portal_action($1,$2::jsonb)',[action,JSON.stringify(payload)]);
 await asUser(owner);
 await assert.rejects(()=>db.query('select public.portal_snapshot()'),/REGISTER_REQUIRED/);
 await assert.rejects(()=>call('addPartner',{name:'Test Partner',email:'one@example.com',phone:'0501234567',profession:'Advisor'}),/PARTNER_INACTIVE/);
 await db.exec('reset role');
 await db.query("insert into public.setup_state values(1,encode(sha256(convert_to($1,'UTF8')),'hex'),null,null)",['a'.repeat(64)]);
 await asUser(owner);
 await assert.rejects(()=>db.query('select public.claim_admin(null)'),/SETUP_DENIED/);
 await db.query('select public.claim_admin($1)',['a'.repeat(64)]);
 await assert.rejects(()=>db.query('select public.claim_admin($1)',['a'.repeat(64)]),/SETUP_DENIED/);
 await assert.rejects(()=>db.query('select * from public.leads'),/permission denied/);
 for(const [email,phone]of [['one@example.com','0501234567'],['two@example.com','0502234567']])await call('addPartner',{name:'Test Partner',email,phone,profession:'Advisor'});
 const snapshot=async()=> (await db.query('select public.portal_snapshot() as data')).rows[0].data;
 let data=await snapshot();assert.equal(data.user.role,'admin');assert.equal(data.settings.commission_mode,'unset');
 const first=data.partners.find(p=>p.email==='one@example.com'),second=data.partners.find(p=>p.email==='two@example.com');
 await asUser(p1);await call('register',{name:'Partner One',phone:'0501234567',profession:'Advisor',consent:true});
 await asUser(p2);await call('register',{name:'Partner Two',phone:'0502234567',profession:'Advisor',consent:true});
 await asUser(p1);
 await assert.rejects(()=>call('addLead',{name:'Client One',phone:'0505555555',purpose:'purchase',consent:false}),/CONSENT_REQUIRED/);
 await call('addLead',{name:'Client One',phone:'+972505555555',purpose:'purchase',consent:true,partnerId:second.id});
 data=await snapshot();assert.equal(data.leads.length,1);assert.equal(data.leads[0].partner_id,first.id);assert.equal(data.leads[0].phone,'••• 5555');
 const lead=data.leads[0].id;
 await assert.rejects(()=>call('saveSettings',{businessName:'Hijacked'}),/ADMIN_ONLY/);
 await asUser(p2);assert.equal((await snapshot()).leads.length,0);
 await asUser(owner);
 await assert.rejects(()=>call('addLead',{name:'Duplicate',phone:'050-555-5555',purpose:'other',consent:true}),/duplicate key/);
 await call('updateLead',{id:lead,status:'paid',notes:'Private',feeReceived:800000});
 assert.equal((await snapshot()).leads[0].commission_amount,null);
 await call('saveSettings',{businessName:'Kesher',advisorName:'Advisor',contactEmail:'',contactPhone:'',commissionMode:'fixed',commissionValue:100000});
 assert.equal((await snapshot()).leads[0].commission_amount,null);
 await assert.rejects(()=>call('commission',{id:lead,amount:100000,status:'paid'}),/APPROVAL_REQUIRED/);
 await call('commission',{id:lead,amount:100000,status:'approved'});
 await call('commission',{id:lead,amount:100000,status:'paid'});
 await assert.rejects(()=>call('commission',{id:lead,amount:1,status:'approved'}),/COMMISSION_LOCKED/);
 await assert.rejects(()=>call('updateLead',{id:lead,status:'lost',notes:'',feeReceived:800000}),/COMMISSION_LOCKED/);
 await asUser(p1);data=await snapshot();assert.equal(data.leads[0].notes,'');assert.equal(data.leads[0].fee_received,0);assert.equal(data.leads[0].commission_rule,null);assert.equal(data.leads[0].commission_amount,100000);
 await asUser(owner);await call('partnerStatus',{id:first.id,status:'paused'});
 await asUser(p1);await assert.rejects(()=>snapshot(),/PARTNER_PAUSED/);
 await db.exec('reset role;set role anon');
 await assert.rejects(()=>db.query('select public.portal_snapshot()'),/permission denied/);
 await assert.rejects(()=>db.query('select * from public.settings'),/permission denied/);
 const info=(await db.query('select public.referral_info($1) as data',[second.code])).rows[0].data;assert.equal(info.settings.commission_value,undefined);
 await db.query('select public.submit_referral($1,$2::jsonb)',[second.code,JSON.stringify({name:'Public Client',phone:'0506666666',purpose:'refinance',consent:true})]);
 await asUser(p2);assert.equal((await snapshot()).leads.length,1);
 await db.exec('reset role');
 await db.exec(await readFile(new URL('../supabase/campaign.sql',import.meta.url),'utf8'));
 await asUser(p2);await assert.rejects(()=>db.query('select public.save_campaign($1::jsonb)',[JSON.stringify({})]),/ADMIN_ONLY/);
 await asUser(owner);await db.query('select public.save_campaign($1::jsonb)',[JSON.stringify({websiteUrl:'https://mayfn.co.il/',headline:'מאי פיננסים',description:'ייעוץ משכנתאות וליווי אישי',benefits:'ליווי אישי',logoUrl:'',published:false})]);
 await db.exec('reset role;set role anon');
 let ci=(await db.query('select public.referral_info($1) as data',[second.code])).rows[0].data;assert.equal(ci.settings.campaign,null);
 await db.query('select public.record_referral_visit($1)',[second.code]);
 await assert.rejects(()=>db.query('select * from public.campaign'),/permission denied/);
 await asUser(owner);await db.query('select public.save_campaign($1::jsonb)',[JSON.stringify({websiteUrl:'https://mayfn.co.il/',headline:'מאי פיננסים',description:'ייעוץ משכנתאות וליווי אישי',benefits:'ליווי אישי',logoUrl:'',published:true})]);
 await db.exec('reset role;set role anon');ci=(await db.query('select public.referral_info($1) as data',[second.code])).rows[0].data;assert.equal(ci.settings.campaign.websiteUrl,'https://mayfn.co.il/');
 await db.close();
});
